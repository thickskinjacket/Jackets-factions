function GAMEMODE:ApplyARC9Settings()
    for name, value in pairs(self.ARC9_SETTINGS) do
        if not GetConVar(name) then
            ErrorNoHalt(string.format("[Garrys Factions] ARC9 convar not found: %s\n", name))
            continue
        end

        RunConsoleCommand(name, tostring(value))
    end
end

timer.Simple(0, function()
    GAMEMODE:ApplyARC9Settings()
end)

